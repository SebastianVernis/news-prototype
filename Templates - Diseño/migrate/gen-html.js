function getArticleScript(site) {
    var s = '';
    s += '    (async function() {\n';
    s += "        var params = new URLSearchParams(location.search);\n";
    s += "        var slug = params.get('slug');\n";
    s += '        if (!slug) { showError(); return; }\n';
    s += '        try {\n';
    s += "            var res = await fetch('" + API_BASE + "/api/articles/' + encodeURIComponent(slug));\n";
    s += "            if (!res.ok) throw new Error('not found');\n";
    s += '            var data = await res.json(); var a = data.article;\n';
    s += "            if (!a) throw new Error('empty');\n";
    s += '            renderArticle(a);\n';
    s += '        } catch(e) { showError(); }\n\n';
    s += '        function renderArticle(a) {\n';
    s += "            document.title = (a.title || 'Articulo') + ' - " + site.name + "';\n";
    s += "            var d=document.getElementById('page-desc'); if(d) d.content=a.excerpt||'';\n";
    s += "            var cat=a.category||'',cs=cat.toLowerCase().replace(/\\s+/g,'-');\n";
    s += "            var b=document.getElementById('art-category-badge'); if(b){b.textContent=cat;b.className='article-category-badge cat-'+cs;}\n";
    s += "            var bc=document.getElementById('art-category-breadcrumb'); if(bc) bc.textContent=cat;\n";
    s += "            var t=document.getElementById('art-title'); if(t) t.textContent=a.title||'';\n";
    s += "            var au=document.getElementById('art-author'); if(au) au.textContent=a.author||'Redaccion';\n";
    s += "            var dt=document.getElementById('art-date'); if(dt) dt.textContent=a.publishedAt?new Date(a.publishedAt).toLocaleDateString('es-MX',{year:'numeric',month:'long',day:'numeric'}):'';\n";
    s += "            var iw=document.getElementById('art-image-wrapper'),im=document.getElementById('art-image');\n";
    s += "            if(a.imageUrl&&im){im.src=a.imageUrl;im.alt=a.title||'';}else if(iw)iw.style.display='none';\n";
    s += "            var body=document.getElementById('art-body');\n";
    s += "            if(body){var c=a.content||'';if(!c)c='<p>'+(a.excerpt||'')+'</p>';else if(!c.includes('<p>')&&!c.includes('<div>'))c=c.split(/\\n\\n+/).map(function(p){return'<p>'+p.trim()+'</p>';}).join('');body.innerHTML=c;}\n";
    s += "            var url=encodeURIComponent(location.href),txt=encodeURIComponent(a.title||'');\n";
    s += "            var fb=document.getElementById('share-fb'),tw=document.getElementById('share-tw'),wa=document.getElementById('share-wa');\n";
    s += "            if(fb)fb.href='https://www.facebook.com/sharer/sharer.php?u='+url;\n";
    s += "            if(tw)tw.href='https://twitter.com/intent/tweet?url='+url+'&text='+txt;\n";
    s += "            if(wa)wa.href='https://wa.me/?text='+txt+'%20'+url;\n";
    s += "            document.getElementById('article-loading').style.display='none';\n";
    s += "            document.getElementById('article-content').style.display='block';\n";
    s += '        }\n';
    s += '        function showError() {\n';
    s += "            document.getElementById('article-loading').style.display='none';\n";
    s += "            document.getElementById('article-error').style.display='block';\n";
    s += '        }\n';
    s += '    })();\n';
    return s;
}

