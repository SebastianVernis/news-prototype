    s += "            document.getElementById('cat-loading').style.display='none';\n";
    s += "            document.getElementById('cat-empty').style.display='block';\n";
    s += '        }\n';
    s += '        function renderCard(a) {\n';
    s += "            var s=a.slug||'',img=a.imageUrl||'../logo.png',c=a.category||'" + label + "';\n";
    s += "            var cs=c.toLowerCase().replace(/\\s+/g,'-'),t=esc(a.title||''),ex=esc(a.excerpt||'');\n";
