    s += '        }\n    }\n\n';
    s += '    function renderSidebar(articles) {\n';
    s += "        var container = document.getElementById('featured-container');\n";
    s += '        if (!container || !articles.length) return;\n';
    s += '        var main = articles[0], list = articles.slice(1, 6);\n';
    s += '        var listHtml = list.map(function(a) {\n';
