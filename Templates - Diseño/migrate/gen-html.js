    s += '            if (!articles || !articles.length) { hide(); return; }\n';
    s += "            var grid = document.getElementById('cat-grid');\n";
    s += '            grid.innerHTML = articles.map(renderCard).join("");\n';
    s += "            document.getElementById('cat-loading').style.display='none';\n";
    s += "            grid.style.display='';\n";
    s += '        } catch(e) { hide(); }\n\n';
