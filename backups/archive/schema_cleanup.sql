-- BACKUP Y LIMPIEZA COMPLETA DEL ESQUEMA
-- Elimina todas las foreign keys problemáticas
-- ============================================================

-- 1. Verificar tablas existentes
SELECT name FROM sqlite_master WHERE type='table' ORDER BY name;

-- 2. Crear backups de todas las tablas importantes
CREATE TABLE IF NOT EXISTS BACKUP_ARTICULOS_ORIGINALES AS SELECT * FROM ARTICULOS_ORIGINALES;
CREATE TABLE IF NOT EXISTS BACKUP_ARTICULOS_PARAFRASEADOS AS SELECT * FROM ARTICULOS_PARAFRASEADOS;
CREATE TABLE IF NOT EXISTS BACKUP_REVISION_CONTENIDO AS SELECT * FROM REVISION_CONTENIDO;
CREATE TABLE IF NOT EXISTS BACKUP_ARTICULOS_CMS AS SELECT * FROM ARTICULOS_CMS;
CREATE TABLE IF NOT EXISTS BACKUP_SITIOS AS SELECT * FROM SITIOS;
CREATE TABLE IF NOT EXISTS BACKUP_CATEGORIAS AS SELECT * FROM CATEGORIAS;
CREATE TABLE IF NOT EXISTS BACKUP_USUARIOS AS SELECT * FROM USUARIOS;

-- 3. Verificar backups
SELECT 'BACKUP_ARTICULOS_ORIGINALES' as tabla, COUNT(*) as registros FROM BACKUP_ARTICULOS_ORIGINALES
UNION ALL SELECT 'BACKUP_ARTICULOS_PARAFRASEADOS', COUNT(*) FROM BACKUP_ARTICULOS_PARAFRASEADOS
UNION ALL SELECT 'BACKUP_REVISION_CONTENIDO', COUNT(*) FROM BACKUP_REVISION_CONTENIDO
UNION ALL SELECT 'BACKUP_ARTICULOS_CMS', COUNT(*) FROM BACKUP_ARTICULOS_CMS;

-- 4. Eliminar tablas con foreign keys (se recrearán sin FK)
DROP TABLE IF EXISTS REVISION_CONTENIDO;
DROP TABLE IF EXISTS METRICAS_CONTENIDO;
DROP TABLE IF EXISTS LEGALES;
DROP TABLE IF EXISTS CANALES_EXTERNOS;
DROP TABLE IF EXISTS MENUS_NAVEGACION;
DROP TABLE IF EXISTS TICKER_FINANCIALS;
DROP TABLE IF EXISTS TICKER_HEADLINES;

-- 5. Recrear REVISION_CONTENIDO sin foreign keys
CREATE TABLE REVISION_CONTENIDO (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  ID_ORIGEN TEXT,
  TIPO_ORIGEN TEXT,
  TITULO_PROPUESTO TEXT,
  CONTENIDO_PROPUESTO TEXT,
  DESCRIPCION_PROPUESTA TEXT,
  SITIO_DESTINO TEXT,
  CATEGORIA TEXT,
  ESTADO TEXT DEFAULT 'PENDIENTE',
  NOTAS_REVISOR TEXT,
  FECHA_PARA_PUBLICAR TEXT,
  FECHA_CREACION TEXT DEFAULT CURRENT_TIMESTAMP,
  URL_IMAGEN TEXT,
  FB_REQUERIDO INTEGER DEFAULT 0,
  ES_BREVE INTEGER DEFAULT 0
);

-- 6. Recrear METRICAS_CONTENIDO sin foreign keys
CREATE TABLE METRICAS_CONTENIDO (
  ID_ARTICULO_PARAFRASEADO TEXT PRIMARY KEY,
  VISTAS INTEGER DEFAULT 0,
  ULTIMA_VISTA TEXT
);

-- 7. Recrear LEGALES sin foreign keys
CREATE TABLE LEGALES (
  ID_SITIO TEXT PRIMARY KEY,
  TERMINOS_CONDICIONES TEXT,
  POLITICA_PRIVACIDAD TEXT,
  POLITICA_COOKIES TEXT,
  ACERCA_DE TEXT,
  CONTACTO_EMAIL TEXT,
  CONTACTO_TELEFONO TEXT,
  CONTACTO_DIRECCION TEXT,
  ULTIMA_ACTUALIZACION TEXT DEFAULT CURRENT_TIMESTAMP
);

-- 8. Recrear CANALES_EXTERNOS sin foreign keys
CREATE TABLE CANALES_EXTERNOS (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  ID_SITIO TEXT,
  TIPO TEXT NOT NULL,
  URL TEXT NOT NULL,
  ETIQUETA TEXT,
  ICONO_CLASE TEXT,
  ORDEN INTEGER DEFAULT 0,
  ACTIVO INTEGER DEFAULT 1
);

-- 9. Recrear MENUS_NAVEGACION sin foreign keys
CREATE TABLE MENUS_NAVEGACION (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  ID_SITIO TEXT,
  ETIQUETA TEXT NOT NULL,
  URL TEXT NOT NULL,
  POSICION TEXT DEFAULT 'HEADER',
  ORDEN INTEGER DEFAULT 0,
  ACTIVO INTEGER DEFAULT 1
);

-- 10. Recrear TICKER_FINANCIALS
CREATE TABLE IF NOT EXISTS TICKER_FINANCIALS (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  SIMBOLO TEXT NOT NULL UNIQUE,
  NOMBRE TEXT NOT NULL,
  VALOR TEXT NOT NULL,
  CAMBIO TEXT DEFAULT '0.00%',
  TENDENCIA TEXT DEFAULT 'up',
  UNIDAD TEXT DEFAULT 'MXN',
  FECHA_ACTUALIZACION TEXT DEFAULT (datetime('now'))
);

-- 11. Recrear TICKER_HEADLINES
CREATE TABLE IF NOT EXISTS TICKER_HEADLINES (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  TITULO TEXT NOT NULL,
  URL TEXT,
  FUENTE TEXT,
  FECHA_CREACION TEXT DEFAULT (datetime('now'))
);

-- 12. Restaurar datos en REVISION_CONTENIDO (solo los que tengan ID_ORIGEN válido)
INSERT INTO REVISION_CONTENIDO (ID, ID_ORIGEN, TIPO_ORIGEN, TITULO_PROPUESTO, CONTENIDO_PROPUESTO, DESCRIPCION_PROPUESTA, SITIO_DESTINO, CATEGORIA, ESTADO, URL_IMAGEN, FB_REQUERIDO, ES_BREVE, FECHA_CREACION)
SELECT ID, ID_ORIGEN, TIPO_ORIGEN, TITULO_PROPUESTO, CONTENIDO_PROPUESTO, DESCRIPCION_PROPUESTA, SITIO_DESTINO, CATEGORIA, ESTADO, URL_IMAGEN, FB_REQUERIDO, ES_BREVE, FECHA_CREACION
FROM BACKUP_REVISION_CONTENIDO;

-- 13. Verificar resultado final
SELECT 'ARTICULOS_ORIGINALES' as tabla, COUNT(*) as registros FROM ARTICULOS_ORIGINALES
UNION ALL SELECT 'ARTICULOS_PARAFRASEADOS', COUNT(*) FROM ARTICULOS_PARAFRASEADOS
UNION ALL SELECT 'REVISION_CONTENIDO', COUNT(*) FROM REVISION_CONTENIDO
UNION ALL SELECT 'ARTICULOS_CMS', COUNT(*) FROM ARTICULOS_CMS;

-- 14. Verificar que no hay foreign keys
SELECT name, sql FROM sqlite_master WHERE type='table' AND sql LIKE '%FOREIGN KEY%';
