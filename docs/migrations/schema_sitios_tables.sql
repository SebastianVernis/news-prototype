-- Schema para 27 tablas ARTICULOS_SITIO_{SLUG}
-- Cada tabla rastrea el estado individual de artículos por sitio
-- Actualizado: 2026-03-11
-- Nota: WEB_FECHA, WEB_URL y WEB_PUBLICADO eliminadas - todos los artículos en estas tablas están publicados
-- La fecha y URL se obtienen dinámicamente de ARTICULOS_PARAFRASEADOS

