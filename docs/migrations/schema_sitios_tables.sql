-- 1. Radio Cinco Noticias
CREATE TABLE IF NOT EXISTS ARTICULOS_SITIO_RADIOCINCONOTICIAS (
  ID TEXT PRIMARY KEY,
  ID_PARAFRASEADO TEXT NOT NULL,
  FB_PUBLICADO INTEGER DEFAULT 0,
  FB_FECHA TEXT,
  FB_POST_ID TEXT,
  FECHA_ASIGNACION TEXT,
  FECHA_CREACION TEXT DEFAULT (datetime('now')),
  FOREIGN KEY (ID_PARAFRASEADO) REFERENCES ARTICULOS_PARAFRASEADOS(ID)
);
CREATE INDEX IF NOT EXISTS idx_sitio_radiocinconoticias_fb ON ARTICULOS_SITIO_RADIOCINCONOTICIAS(FB_PUBLICADO);

